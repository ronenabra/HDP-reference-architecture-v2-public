'use strict';
/** Actual selected-source authentication, browser-bound resume and separate confidential SMART exchange. */
const { test, expect } = require('@playwright/test');
const pcm = process.env.PCM_UI_PCM_URL, doctor = process.env.PCM_UI_SP_URL;
const headers = { Accept: 'application/json', 'x-admin-password': process.env.PCM_UI_ADMIN_PASSWORD };
test('HMO self verification resumes the original SMART request without automatic approval @smoke', async ({ browser, page }, info) => {
    test.setTimeout(90000);
    const touch = info.project.name === 'chromium-mobile';
    const context = touch ? await browser.newContext({ hasTouch: true, isMobile: true, viewport: { width: 390, height: 844 }, ignoreHTTPSErrors: true }) : null;
    if (context) page = await context.newPage();
    const snapshot = await page.request.get(`${pcm}/admin/backup`, { headers }); expect(snapshot.ok()).toBeTruthy(); const config = (await snapshot.json()).teamConfig;
    const count = async () => { const r = await page.request.get(`${pcm}/admin/consents`, { headers }); expect(r.ok()).toBeTruthy(); return (await r.json()).consents.length; };
    const before = await count(), protocol = [];
    page.on('request', request => { if (/\/authorize(?:\?|\/decision)|\/callback\?|\/sandbox\/authentication\/(?:start|verify)/.test(request.url())) protocol.push(new URL(request.url()).pathname); });
    await page.goto(doctor); await page.getByRole('button', { name: 'Tools', exact: true }).click(); await page.locator('[data-help-key="doctor.smart-start"]').click();
    const original = page.url(), transaction = await page.locator('[name="transaction_id"]').inputValue();
    expect(new URL(original).protocol).toBe('https:');
    expect(await page.locator('[name="patient"]:checked').count()).toBe(0);
    await page.getByRole('link', { name: 'Test sign-in through an HMO', exact: true }).click();
    const continuation = page.url(); expect(new URL(continuation).searchParams.get('smart')).toBe(transaction);
    const intruder = await browser.newContext({ ignoreHTTPSErrors: true });
    const forbidden = await intruder.request.get(continuation); expect(forbidden.status()).toBe(400); await intruder.close();
    await page.locator('#home-hmo').selectOption(config.healthOrganizations[0].dataSourceOrganization.id);
    await page.locator('#identifier').fill('000000018'); await page.locator('#birthDate').fill('1980-01-02');
    await page.getByRole('button', { name: 'Check HMO and show verification step', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'Verify code', exact: true })).toBeVisible(); expect(page.url()).toBe(continuation);
    await page.locator('details').filter({ has: page.locator('form[action$="/local-code"]') }).locator('summary').click();
    await page.getByRole('button', { name: 'Show local code', exact: true }).click();
    const code = (await page.locator('[data-local-code]').innerText()).match(/\b\d{6}\b/)[0];
    await page.locator('#code').fill(code); await page.getByRole('button', { name: 'Verify code', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'Verified test patient', exact: true })).toBeVisible();
    const back = page.getByRole('link', { name: 'Return to SMART request', exact: true });
    await page.getByRole('checkbox', { name: 'Explain this page' }).check();
    if (touch) await back.locator('xpath=following-sibling::button[@data-help-for][1]').tap(); else await back.focus();
    await expect(page.getByRole('tooltip')).toContainText('explicit decision'); await page.keyboard.press('Escape');
    await page.getByRole('checkbox', { name: 'Explain this page' }).uncheck(); await back.click();
    expect(await page.locator('[name="transaction_id"]').inputValue()).toBe(transaction);
    await expect(page.locator('[value="authenticated-self"]')).toBeChecked();
    await page.reload(); expect(await page.locator('[name="transaction_id"]').inputValue()).toBe(transaction);
    expect(protocol.filter(path => path.endsWith('/callback')).length).toBe(0); expect(await count()).toBe(before);
    await page.locator('button[name="decision"][value="approve"]').click();
    await expect(page.getByText('SMART code exchange completed', { exact: false })).toBeVisible();
    // Fresh same-browser request uses the current self session; no second OTP or automatic decision.
    await page.getByRole('button', { name: 'Tools', exact: true }).click(); await page.locator('[data-help-key="doctor.smart-start"]').click();
    await expect(page.locator('[value="authenticated-self"]')).toBeChecked();
    expect(await page.locator('[name="transaction_id"]').inputValue()).not.toBe(transaction);
    await page.locator('button[name="decision"][value="cancel"]').click();
    expect(await count()).toBe(before);
    await info.attach('continuation-boundaries', { contentType: 'application/json', body: Buffer.from(JSON.stringify({ actualSourceAuthentication: true, originalRequestResumed: true, explicitDecision: true, freshSessionReused: true, crossBrowserRejected: true, consentDelta: 0, browserOperations: protocol })) });
    await context?.close();
});
