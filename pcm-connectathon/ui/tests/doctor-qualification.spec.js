test('QUALIFY all four notices/sampling gates and independent SMART launch leave clinical Consent unchanged', async ({ browser }, info) => {
    const fixture = await require(path.join(root, 'test-support/doctor-qualification-fixture')).startDoctorQualificationFixture();
    const context = await browser.newContext({ ignoreHTTPSErrors: true, hasTouch: info.project.name === 'mobile', isMobile: info.project.name === 'mobile', viewport: { width: info.project.name === 'mobile' ? 390 : 1440, height: 1000 } });
    const page = await context.newPage(), states = [];
    try {
        const { EXTENSIONS } = require(path.join(root, 'src/shared/pcm-contract'));
        // Omit only optional public descriptions; the PCM-owned service definition remains unchanged.
        for (const item of [fixture.services.definitions[4], fixture.services.registrationsA[4]]) {
            const resource = structuredClone(fixture.store.get('HealthcareService', item.id));
            delete resource.extraDetails;
            resource.extension = resource.extension.filter(value => value.url !== EXTENSIONS.informationBucket);
            fixture.store.update(resource);
        }
        for (const preset of ['strict', 'connectathon-mtls', 'connectathon-balanced', 'connectathon-easy']) {
            const policy = fixture.preset(preset);
            await page.goto(fixture.doctorBase + '/?identity=hospital-a');
            await expect(page.locator('[aria-label="Sandbox notice"]')).toContainText(policy.resultLabel);
            await expect(page.locator('[aria-label="Sandbox notice"]')).toContainText('Patient/source context apply in every preset');
            await page.locator('#service-id').selectOption(fixture.services.registrationsA[4].id);
            for (const fact of ['purpose', 'data', 'history']) await expect(page.locator(`[data-service-fact="${fact}"]`)).toHaveText('Not provided by PCM');
            await expect(page.locator(`#service-id option[value="${fixture.services.registrationsA[4].id}"]`)).toBeEnabled();
            await page.getByRole('checkbox', { name: 'Explain this page' }).check();
            await page.locator('#doctor-identity').focus();
            await expect(page.getByRole('tooltip')).toContainText('Use the primary registered application and its configured credentials');
            if (preset === 'connectathon-mtls') await page.screenshot({ path: info.outputPath('application-help.png'), fullPage: true });
            await page.getByRole('button', { name: 'Dismiss explanation' }).click(); await expect(page.locator('#doctor-identity')).toBeFocused();
            await page.getByRole('checkbox', { name: 'Explain this page' }).uncheck();
            await page.screenshot({ path: info.outputPath(`preset-${preset}-notice.png`), fullPage: true });
            await page.locator('[data-patient-library]').click(); await page.locator('[data-library-view="sample"]').click();
            await expect(page.locator('[aria-label="Sandbox notice"]')).toContainText('Synthetic patients only');
            if (preset === 'strict') {
                await expect(page.locator('#sample-load')).toBeDisabled(); await expect(page.locator('#sample-state')).toContainText('Strict');
                await page.getByRole('checkbox', { name: 'Explain this page' }).check();
                if (info.project.name === 'mobile') {
                    await page.locator('#sample-load').scrollIntoViewIfNeeded(); const r = await page.locator('#sample-load').boundingBox(); await page.touchscreen.tap(r.x + r.width / 2, r.y + r.height / 2);
                } else await page.locator('#sample-load').hover();
                await expect(page.getByRole('tooltip')).toContainText('ordinary PCM token');
                await page.getByRole('button', { name: 'Dismiss explanation' }).click();
                await expect(page.getByRole('checkbox', { name: 'Explain this page' })).toBeFocused();
            } else await expect(page.locator('#sample-load')).toBeEnabled();
            states.push({ preset, resultLabel: policy.resultLabel, samplingEnabled: preset !== 'strict' });
        }
        expect(fixture.requests.filter(row => row.kind === 'sandbox_patient_sample' || row.kind === 'data_source_access')).toEqual([]);
        await page.goto(fixture.doctorBase + '/?identity=hospital-a');
        await page.getByRole('button', { name: 'Tools', exact: true }).click();
        const before = fixture.store.getAll('Consent');
        await page.getByRole('link', { name: 'Test SMART application launch', exact: true }).click();
        await expect(page.locator('form[action$="/authorize/decision"]')).toBeVisible();
        await expect(page.locator('body')).toContainText('SMART');
        await expect(page.locator('body')).not.toContainText('Enter the verification code');
        expect(new URL(page.url()).searchParams.get('redirect_uri')).toBe(fixture.doctorBase + '/callback');
        await page.locator('button[name="decision"][value="cancel"]').click();
        await expect(page.getByText('SMART test cancelled.', { exact: true })).toBeVisible();
        expect(fixture.store.getAll('Consent')).toEqual(before);
        expect(fixture.requests.filter(row => row.kind === 'sandbox_patient_sample' || row.kind === 'data_source_access')).toEqual([]);
        await page.screenshot({ path: info.outputPath('smart-separate-cancelled.png'), fullPage: true });
        fs.writeFileSync(info.outputPath('preset-smart-separation.json'), JSON.stringify({ states, requests: fixture.requests, clinicalConsentDelta: 0, hmoOtpStarted: false }, null, 2));
    } finally { await context.close(); await fixture.close(); }
});
